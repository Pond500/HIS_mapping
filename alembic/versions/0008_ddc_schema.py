def _seed_checkup_lists():
    """The department's lab catalogue, generated from app/template.py (D23-ก).

    lower_limit and upper_limit stay NULL. Our template's lo/hi is a *plausible*
    range for catching unit errors — "no adult has a haematocrit of 400" — which
    is a different number from the clinical *normal* range this column means.
    Guessing one from the other would put invented medical thresholds into the
    department's schema. They stay empty until the department supplies theirs
    (D23-ถาม).

    The unit recorded is the one the value is *stored* in, which for wbc and plt
    is the department's 10^3/uL and not our canonical cells/µL.
    """
    from app.template import TEMPLATE_FIELDS, ddc_unit

    cat = {n: i for i, n in enumerate(CATEGORIES, start=1)}
    rows = [{"id": i,
             "name": f.column,
             "category_id": cat[f.group],
             "unit": ddc_unit(f.column),
             "description": "",
             "lower_limit": None,
             "upper_limit": None,
             "column_name": f.column}
            for i, f in enumerate((f for f in TEMPLATE_FIELDS if f.group != "person"), start=1)]
    op.bulk_insert(
        sa.table("checkup_lists",
                 sa.column("id", sa.Integer), sa.column("name", sa.String),
                 sa.column("category_id", sa.Integer), sa.column("unit", sa.String),
                 sa.column("description", sa.Text), sa.column("lower_limit", sa.Float),
                 sa.column("upper_limit", sa.Float), sa.column("column_name", sa.String)),
        rows)


